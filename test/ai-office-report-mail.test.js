test('explicit confirmation and validated bounded PDF are required before any send or reservation', () => fixture(async f => {
  await f.setup();
  const huge = Buffer.alloc(MAX_REPORT_PDF_BYTES + 1, 32).toString('base64');
  for (const input of [
    request({confirmation: false}), request({id: '../escape'}), request({reportTitle: 'bad\r\nBcc: victim@gmail.com'}),
    request({reportTitle: ''}), request({reportTitle: 'a'.repeat(161)}), request({to: 'other@gmail.com'}),
    request({recipient: sender}), request({cc: sender}), request({bcc: sender}),
    request({pdfBase64: 'not base64'}), request({pdfBase64: 'YWJj'}), request({pdfBase64: huge}),
    request({pdfBase64: Buffer.from('%PDF-1.7\nmissing EOF').toString('base64')}),
  ]) await assert.rejects(f.mail.send(input), error => /^office_report_mail_/.test(error.code));
  assert.equal(f.calls.length, 0);
  assert.equal(fs.existsSync(path.join(f.stateDir, 'report-mail/attempts')), false);
}));

