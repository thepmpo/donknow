test('tampered encrypted config and missing key are preserved and refuse replacement or delivery', () => fixture(async f => {
  await f.setup();
  const root = path.join(f.stateDir, 'report-mail'), configPath = path.join(root, 'config.json');
  const config = JSON.parse(fs.readFileSync(configPath));
  config.tag = '0'.repeat(32); fs.writeFileSync(configPath, JSON.stringify(config), {mode: 0o600});
  const tampered = fs.readFileSync(configPath);
  assert.equal(f.mail.status().configured, false);
  assert.equal(f.mail.status().errorCode, 'office_report_mail_configuration_unreadable');
  await assert.rejects(f.setup(), /office_report_mail_configuration_unreadable/);
  await assert.rejects(f.mail.send(request()), /office_report_mail_configuration_unreadable/);
  assert.deepEqual(fs.readFileSync(configPath), tampered);
  fs.unlinkSync(path.join(root, 'key.bin'));
  await assert.rejects(f.setup(), /office_report_mail_configuration_unreadable/);
  assert.equal(fs.existsSync(path.join(root, 'key.bin')), false);
  assert.equal(f.calls.length, 0);
}));

test('symlinked state, config, ledger and public key modes fail closed without touching targets', () => fixture(async f => {
  const outside = path.join(f.stateDir, 'outside'); fs.mkdirSync(outside);
  fs.symlinkSync(outside, path.join(f.stateDir, 'report-mail'));
  await assert.rejects(f.setup(), /office_report_mail_private_directory_required/);
  assert.deepEqual(fs.readdirSync(outside), []);
  fs.unlinkSync(path.join(f.stateDir, 'report-mail'));
  await f.setup();
  const root = path.join(f.stateDir, 'report-mail');
  fs.chmodSync(path.join(root, 'key.bin'), 0o644);
  await assert.rejects(f.mail.send(request()), /office_report_mail_configuration_unreadable/);
  fs.chmodSync(path.join(root, 'key.bin'), 0o600);
  fs.symlinkSync(outside, path.join(root, 'attempts'));
  await assert.rejects(f.mail.send(request()), /office_report_mail_private_directory_required/);
  assert.deepEqual(fs.readdirSync(outside), []);
  fs.unlinkSync(path.join(root, 'config.json'));
  fs.symlinkSync(path.join(outside, 'not-created'), path.join(root, 'config.json'));
  await assert.rejects(f.setup(), /office_report_mail_configuration_unreadable/);
  assert.equal(fs.existsSync(path.join(outside, 'not-created')), false);
  assert.equal(fs.lstatSync(path.join(root, 'config.json')).isSymbolicLink(), true);
}));
